def translate(text, locale: str | None) -> str:
    """Translate *text* to English when *locale* is English."""
    value = str(text)
    if str(locale or 'ar').split('-')[0].lower() == 'en':
        return AR_TO_EN.get(value) or CATALOG.get(value, value)
    return value
